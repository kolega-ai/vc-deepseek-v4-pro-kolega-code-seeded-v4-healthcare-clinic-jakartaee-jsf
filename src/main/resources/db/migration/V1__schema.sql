-- =====================================================================
-- Oakfield Clinic Patient Portal - V1 baseline schema
-- Owned by Flyway. JPA runs with hbm2ddl.auto=validate against this.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Identity and accounts
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(255) NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    full_name            VARCHAR(120) NOT NULL,
    role                 VARCHAR(20)  NOT NULL,
    status               VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    phone                VARCHAR(30),
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at        TIMESTAMP,
    password_changed_at  TIMESTAMP
);

CREATE TABLE provider (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES app_user (id),
    first_name   VARCHAR(120) NOT NULL,
    last_name    VARCHAR(120) NOT NULL,
    title        VARCHAR(80),
    specialty    VARCHAR(120),
    npi          VARCHAR(20) NOT NULL UNIQUE,
    phone        VARCHAR(30),
    email        VARCHAR(255),
    active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patient (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT REFERENCES app_user (id),
    first_name                VARCHAR(120) NOT NULL,
    last_name                 VARCHAR(120) NOT NULL,
    date_of_birth             DATE NOT NULL,
    gender                    VARCHAR(20),
    phone                     VARCHAR(30),
    email                     VARCHAR(255),
    address_line1             VARCHAR(200),
    city                      VARCHAR(80),
    state                     VARCHAR(40),
    postal_code               VARCHAR(20),
    emergency_contact_name    VARCHAR(120),
    emergency_contact_phone   VARCHAR(30),
    insurance_provider        VARCHAR(120),
    insurance_policy_number   VARCHAR(80),
    insurance_group_number    VARCHAR(80),
    primary_provider_id       BIGINT REFERENCES provider (id),
    medical_alert             VARCHAR(500),
    active                    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Scheduling reference data (fee schedule is a seeded reference table:
-- amounts are read server-side and never accepted from clients)
-- ---------------------------------------------------------------------
CREATE TABLE appointment_type (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(20) NOT NULL UNIQUE,
    name             VARCHAR(120) NOT NULL,
    description      VARCHAR(500),
    duration_minutes INT NOT NULL,
    fee_amount       NUMERIC(10,2) NOT NULL,
    fee_currency     VARCHAR(3) NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order       INT NOT NULL DEFAULT 0
);

CREATE TABLE provider_schedule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id     BIGINT NOT NULL REFERENCES provider (id),
    day_of_week     INT NOT NULL,           -- 1=Mon .. 7=Sun
    start_time      TIME NOT NULL,
    end_time        TIME NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from  DATE,
    effective_to    DATE
);

CREATE TABLE provider_blocked_date (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id  BIGINT NOT NULL REFERENCES provider (id),
    block_date   DATE NOT NULL,
    reason       VARCHAR(200),
    CONSTRAINT uq_provider_block UNIQUE (provider_id, block_date)
);

-- ---------------------------------------------------------------------
-- Appointments and clinical records
-- ---------------------------------------------------------------------
CREATE TABLE appointment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id           BIGINT NOT NULL REFERENCES patient (id),
    provider_id          BIGINT NOT NULL REFERENCES provider (id),
    appointment_type_id  BIGINT NOT NULL REFERENCES appointment_type (id),
    start_time           TIMESTAMP NOT NULL,
    end_time             TIMESTAMP NOT NULL,
    status               VARCHAR(20) NOT NULL,
    reason               VARCHAR(1000),
    notes                VARCHAR(2000),
    checked_in_at        TIMESTAMP,
    cancelled_reason     VARCHAR(500),
    created_by_user_id   BIGINT REFERENCES app_user (id),
    created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_appt_provider_start ON appointment (provider_id, start_time);
CREATE INDEX idx_appt_patient       ON appointment (patient_id);
CREATE INDEX idx_appt_status        ON appointment (status);

CREATE TABLE visit_summary (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id    BIGINT NOT NULL UNIQUE REFERENCES appointment (id),
    patient_id        BIGINT NOT NULL REFERENCES patient (id),
    provider_id       BIGINT NOT NULL REFERENCES provider (id),
    status            VARCHAR(20) NOT NULL,   -- DRAFT | RELEASED
    diagnosis_text    VARCHAR(4000),
    care_instructions VARCHAR(4000),
    follow_up_plan    VARCHAR(2000),
    clinician_notes   VARCHAR(4000),          -- internal: never patient-visible
    released_at       TIMESTAMP,
    released_by       BIGINT REFERENCES app_user (id),
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prescription (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id             BIGINT NOT NULL REFERENCES patient (id),
    provider_id            BIGINT NOT NULL REFERENCES provider (id),
    appointment_id         BIGINT REFERENCES appointment (id),
    medication_name        VARCHAR(200) NOT NULL,
    dosage                 VARCHAR(120) NOT NULL,
    frequency              VARCHAR(120) NOT NULL,
    instructions           VARCHAR(1000),
    status                 VARCHAR(20) NOT NULL,       -- ACTIVE | DISCONTINUED | COMPLETED
    refill_status          VARCHAR(20) NOT NULL DEFAULT 'NONE',
    refill_requested_at    TIMESTAMP,
    refill_request_note    VARCHAR(1000),
    refill_response_note   VARCHAR(1000),
    refill_decided_by      BIGINT REFERENCES app_user (id),
    refill_decided_at      TIMESTAMP,
    refill_transmit_status VARCHAR(20),                 -- PENDING | SENT | FAILED
    refill_transmit_ref    VARCHAR(80),
    refills_remaining      INT NOT NULL DEFAULT 0,
    created_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Documents (files on local disk, metadata here)
-- ---------------------------------------------------------------------
CREATE TABLE document (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     BIGINT NOT NULL REFERENCES patient (id),
    uploaded_by    BIGINT NOT NULL REFERENCES app_user (id),
    category       VARCHAR(20) NOT NULL,        -- FORM | CLINICAL
    title          VARCHAR(200) NOT NULL,
    description    VARCHAR(1000),
    original_name  VARCHAR(255) NOT NULL,
    stored_name    VARCHAR(100) NOT NULL UNIQUE,
    content_type   VARCHAR(120) NOT NULL,
    size_bytes     BIGINT NOT NULL,
    sha256         VARCHAR(64) NOT NULL,
    status         VARCHAR(20) NOT NULL,        -- SUBMITTED | VERIFIED | REJECTED | ARCHIVED
    review_note    VARCHAR(1000),
    reviewed_by    BIGINT REFERENCES app_user (id),
    reviewed_at    TIMESTAMP,
    uploaded_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_doc_patient ON document (patient_id);

-- ---------------------------------------------------------------------
-- Messaging
-- ---------------------------------------------------------------------
CREATE TABLE message_thread (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       BIGINT NOT NULL REFERENCES patient (id),
    subject          VARCHAR(200) NOT NULL,
    created_by       BIGINT REFERENCES app_user (id),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id        BIGINT NOT NULL REFERENCES message_thread (id),
    sender_user_id   BIGINT REFERENCES app_user (id),   -- NULL = system
    visibility       VARCHAR(20) NOT NULL,              -- PATIENT_VISIBLE | INTERNAL
    body             VARCHAR(4000) NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_msg_thread ON message (thread_id, created_at);

CREATE TABLE thread_read_state (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id     BIGINT NOT NULL REFERENCES message_thread (id),
    user_id       BIGINT NOT NULL REFERENCES app_user (id),
    last_read_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_thread_read UNIQUE (thread_id, user_id)
);

-- ---------------------------------------------------------------------
-- Notifications, audit, jobs, integrations
-- ---------------------------------------------------------------------
CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user (id),
    type       VARCHAR(40) NOT NULL,
    title      VARCHAR(200) NOT NULL,
    body       VARCHAR(1000),
    link       VARCHAR(200),
    read_at    TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notif_user ON notification (user_id, read_at);

-- Append-only audit log. No update or delete path exists in the application;
-- no role can modify these rows through any screen, endpoint, or export.
CREATE TABLE audit_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_user_id BIGINT,
    actor_name   VARCHAR(120),
    actor_role   VARCHAR(20),
    action       VARCHAR(50) NOT NULL,
    target_type  VARCHAR(40),
    target_id    VARCHAR(64),
    before_value VARCHAR(4000),
    after_value  VARCHAR(4000),
    authz_basis  VARCHAR(500),
    request_id   VARCHAR(40),
    ip_address   VARCHAR(45)
);
CREATE INDEX idx_audit_time   ON audit_event (occurred_at);
CREATE INDEX idx_audit_actor  ON audit_event (actor_user_id);
CREATE INDEX idx_audit_action ON audit_event (action);
CREATE INDEX idx_audit_target ON audit_event (target_type, target_id);

CREATE TABLE import_job (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               VARCHAR(30) NOT NULL,
    original_name      VARCHAR(255) NOT NULL,
    status             VARCHAR(20) NOT NULL,    -- PENDING | RUNNING | COMPLETED | FAILED
    total_rows         INT NOT NULL DEFAULT 0,
    success_rows       INT NOT NULL DEFAULT 0,
    error_rows         INT NOT NULL DEFAULT 0,
    error_report_name  VARCHAR(100),
    created_by         BIGINT REFERENCES app_user (id),
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at       TIMESTAMP
);

CREATE TABLE export_job (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(30) NOT NULL,
    params       VARCHAR(1000),
    file_name    VARCHAR(120) NOT NULL,
    status       VARCHAR(20) NOT NULL,
    created_by   BIGINT REFERENCES app_user (id),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

CREATE TABLE webhook_subscription (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url         VARCHAR(500) NOT NULL,
    secret      VARCHAR(120) NOT NULL,
    events      VARCHAR(500) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_by  BIGINT REFERENCES app_user (id),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE webhook_delivery (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES webhook_subscription (id),
    event_type      VARCHAR(50) NOT NULL,
    payload         VARCHAR(8000) NOT NULL,
    status          VARCHAR(20) NOT NULL,       -- PENDING | SENT | FAILED
    attempts        INT NOT NULL DEFAULT 0,
    last_error      VARCHAR(1000),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at         TIMESTAMP
);

-- Demo receiver for webhook deliveries (so the workflow is observable locally).
CREATE TABLE webhook_echo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    signature   VARCHAR(200),
    payload     VARCHAR(8000)
);

CREATE TABLE outbox_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel    VARCHAR(10) NOT NULL,            -- EMAIL | SMS
    recipient  VARCHAR(200) NOT NULL,
    subject    VARCHAR(300),
    body       VARCHAR(4000) NOT NULL,
    status     VARCHAR(20) NOT NULL,            -- PENDING | SENT | FAILED
    attempts   INT NOT NULL DEFAULT 0,
    error      VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at    TIMESTAMP
);

CREATE TABLE clinic_setting (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         VARCHAR(80) NOT NULL UNIQUE,
    value       VARCHAR(2000) NOT NULL,
    description VARCHAR(500)
);

-- ---------------------------------------------------------------------
-- Account recovery and invites
-- ---------------------------------------------------------------------
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user (id),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reset_user ON password_reset_token (user_id);

CREATE TABLE invite_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    role       VARCHAR(20) NOT NULL,
    full_name  VARCHAR(120),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at    TIMESTAMP,
    created_by BIGINT REFERENCES app_user (id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Decision tier (authorization) tables.
-- The decision tier loads the acting user's role, scopes, and limits from
-- ITS OWN tables on every request. Client-supplied identity attributes are
-- ignored: role/scope/limit are only ever read from these rows.
-- ---------------------------------------------------------------------
CREATE TABLE decision_session (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id    VARCHAR(64) NOT NULL UNIQUE,
    user_id     BIGINT NOT NULL,
    email       VARCHAR(255) NOT NULL,
    full_name   VARCHAR(120) NOT NULL,
    role        VARCHAR(20) NOT NULL,
    issued_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMP NOT NULL,
    revoked_at  TIMESTAMP,
    ip_address  VARCHAR(45),
    user_agent  VARCHAR(300),
    scopes      VARCHAR(2000) NOT NULL,
    limits      VARCHAR(2000) NOT NULL
);
CREATE INDEX idx_dsession_user ON decision_session (user_id);

CREATE TABLE decision_role_scope (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role   VARCHAR(20) NOT NULL,
    scope  VARCHAR(60) NOT NULL,
    CONSTRAINT uq_role_scope UNIQUE (role, scope)
);

CREATE TABLE decision_scope_limit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role        VARCHAR(20) NOT NULL,
    scope       VARCHAR(60) NOT NULL,
    limit_name  VARCHAR(60) NOT NULL,
    limit_value VARCHAR(200) NOT NULL
);

CREATE TABLE decision_api_key (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    key_hash      VARCHAR(64) NOT NULL UNIQUE,
    key_prefix    VARCHAR(12) NOT NULL,
    scopes        VARCHAR(500) NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_by    BIGINT REFERENCES app_user (id),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at    TIMESTAMP,
    last_used_at  TIMESTAMP
);
